"""IMP-279 (H14): the Claude Code plugin and marketplace.

`plugins/` and `.claude-plugin/marketplace.json` are generated by
`python -m sentinel.adapters --plugin` and never edited by hand. These tests pin
what the generator emits, that the committed copy matches it byte for byte, that
the bundled runtime runs from the plugin folder alone, and that the offline
validator in `/doctor` rejects the mistakes `claude plugin validate` rejects.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from sentinel import plugin_package as pp
from sentinel.adapters import CANONICAL_SKILLS_DIR, RUNTIME_INVOCATION, SKILL_OVERLAYS

REPO_ROOT = Path(__file__).resolve().parents[1]


def _package_files(base: Path) -> dict[str, bytes]:
    return {
        item.relative_to(base).as_posix(): item.read_bytes()
        for item in sorted(base.rglob("*"))
        if item.is_file() and "__pycache__" not in item.parts and item.suffix != ".pyc"
    }


class GeneratedPluginTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.files = pp.expected_plugin_files(REPO_ROOT)

    def _json(self, relative: str) -> dict:
        return json.loads(self.files[relative].decode("utf-8"))

    def test_marketplace_lists_both_plugins_by_relative_path(self) -> None:
        market = self._json(pp.MARKETPLACE_FILE)
        self.assertEqual(market["name"], "ignite-sentinel")
        self.assertIn("name", market["owner"])
        entries = {entry["name"]: entry for entry in market["plugins"]}
        self.assertEqual(set(entries), {pp.PLUGIN_NAME, pp.MCP_PLUGIN_NAME})
        for name, entry in entries.items():
            with self.subTest(plugin=name):
                self.assertEqual(entry["source"], f"./plugins/{name}")
                self.assertNotIn("version", entry, "the version lives only in plugin.json")
        self.assertIs(entries[pp.MCP_PLUGIN_NAME]["defaultEnabled"], False)
        self.assertNotIn("defaultEnabled", entries[pp.PLUGIN_NAME])

    def test_manifest_carries_the_package_version_and_metadata(self) -> None:
        manifest = self._json(f"plugins/{pp.PLUGIN_NAME}/.claude-plugin/plugin.json")
        self.assertEqual(manifest["name"], pp.PLUGIN_NAME)
        self.assertEqual(manifest["version"], pp.project_version(REPO_ROOT))
        self.assertEqual(manifest["license"], "MIT")
        self.assertTrue(manifest["homepage"].startswith("https://"))
        for field in ("description", "author", "repository", "keywords"):
            self.assertIn(field, manifest)

    def test_mcp_plugin_is_off_by_default_and_runs_the_launcher(self) -> None:
        base = f"plugins/{pp.MCP_PLUGIN_NAME}"
        manifest = self._json(f"{base}/.claude-plugin/plugin.json")
        self.assertIs(manifest["defaultEnabled"], False)
        self.assertEqual(manifest["version"], pp.project_version(REPO_ROOT))
        server = self._json(f"{base}/.mcp.json")["mcpServers"]["ignite-sentinel"]
        self.assertEqual(server["args"], ["${CLAUDE_PLUGIN_ROOT}/launcher.py", "--mcp"])

    def test_skills_are_rendered_with_the_plugin_overlay(self) -> None:
        canonical = REPO_ROOT / CANONICAL_SKILLS_DIR
        skill_md = sorted(canonical.glob("*/SKILL.md"))
        self.assertTrue(skill_md)
        overlay = SKILL_OVERLAYS["claude-plugin"]
        rendered_any = False
        for source in skill_md:
            relative = f"plugins/{pp.PLUGIN_NAME}/skills/{source.relative_to(canonical).as_posix()}"
            text = self.files[relative].decode("utf-8")
            if RUNTIME_INVOCATION in source.read_text(encoding="utf-8"):
                rendered_any = rendered_any or overlay in text
        self.assertTrue(rendered_any, "no skill carries the plugin launcher invocation")
        self.assertNotIn(f"plugins/{pp.MCP_PLUGIN_NAME}/skills", " ".join(self.files))

    def test_hooks_file_wraps_the_event_map_and_uses_the_plugin_root(self) -> None:
        hooks = self._json(f"plugins/{pp.PLUGIN_NAME}/hooks/hooks.json")
        command = hooks["hooks"]["PreToolUse"][0]["hooks"][0]["command"]
        self.assertIn('"${CLAUDE_PLUGIN_ROOT}/hooks/deny-governed-artifact-write.py"', command)
        script = self.files[f"plugins/{pp.PLUGIN_NAME}/hooks/deny-governed-artifact-write.py"]
        self.assertEqual(script, (REPO_ROOT / ".claude" / "hooks" / "deny-governed-artifact-write.py").read_bytes())

    def test_each_plugin_bundles_the_runtime_in_source_form(self) -> None:
        source = _package_files(REPO_ROOT / "sentinel")
        for name in (pp.PLUGIN_NAME, pp.MCP_PLUGIN_NAME):
            with self.subTest(plugin=name):
                prefix = f"plugins/{name}/lib/sentinel/"
                bundled = {key[len(prefix):]: value for key, value in self.files.items() if key.startswith(prefix)}
                self.assertEqual(bundled, source)
                self.assertFalse(any(key.endswith(".pyc") for key in bundled))

    def test_least_privilege_layout(self) -> None:
        for relative in self.files:
            with self.subTest(path=relative):
                parts = relative.split("/")
                if parts[0] == "plugins":
                    self.assertNotEqual(parts[2], "bin", "a top-level bin/ is refused by claude.ai org sync")
                    self.assertNotIn(parts[2], ("monitors", ".lsp.json"))
                self.assertNotIn("..", parts)

    def test_committed_plugin_matches_the_generator(self) -> None:
        self.assertEqual(pp.plugin_out_of_sync(REPO_ROOT), [])


class OutOfSyncDetectionTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, True)
        for name in ("sentinel", CANONICAL_SKILLS_DIR, ".claude/hooks"):
            shutil.copytree(REPO_ROOT / name, self.tmp / name, ignore=shutil.ignore_patterns("__pycache__"))
        for name in ("pyproject.toml", "LICENSE"):
            shutil.copy(REPO_ROOT / name, self.tmp / name)
        pp.regenerate_plugin(self.tmp)

    def test_a_fresh_generation_is_in_sync(self) -> None:
        self.assertEqual(pp.plugin_out_of_sync(self.tmp), [])

    def test_a_hand_edit_in_the_bundled_runtime_is_reported(self) -> None:
        target = self.tmp / "plugins" / pp.PLUGIN_NAME / "lib" / "sentinel" / "cli.py"
        target.write_bytes(target.read_bytes() + b"# hand edit\n")
        self.assertTrue(any("lib/sentinel/cli.py" in issue for issue in pp.plugin_out_of_sync(self.tmp)))

    def test_a_stale_file_is_reported_and_removed_on_regeneration(self) -> None:
        stale = self.tmp / "plugins" / pp.PLUGIN_NAME / "lib" / "sentinel" / "gone.py"
        stale.write_text("x", encoding="utf-8")
        self.assertTrue(any("gone.py" in issue for issue in pp.plugin_out_of_sync(self.tmp)))
        pp.regenerate_plugin(self.tmp)
        self.assertFalse(stale.exists())
        self.assertEqual(pp.plugin_out_of_sync(self.tmp), [])

    def test_a_version_bump_reaches_the_manifest(self) -> None:
        pyproject = self.tmp / "pyproject.toml"
        pyproject.write_text(pyproject.read_text(encoding="utf-8").replace('version = "', 'version = "9', 1), encoding="utf-8")
        self.assertTrue(any("plugin.json" in issue for issue in pp.plugin_out_of_sync(self.tmp)))


class BundledRuntimeTests(unittest.TestCase):
    """The plugin folder alone must run: no repo checkout, no installed package."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.tmp = Path(tempfile.mkdtemp())
        cls.plugin = cls.tmp / "cache" / pp.PLUGIN_NAME
        shutil.copytree(REPO_ROOT / "plugins" / pp.PLUGIN_NAME, cls.plugin)
        cls.project = cls.tmp / "project"
        cls.project.mkdir()

    @classmethod
    def tearDownClass(cls) -> None:
        shutil.rmtree(cls.tmp, True)

    def _run(self, args: list[str], stdin: str = "") -> subprocess.CompletedProcess:
        env = {key: value for key, value in os.environ.items() if key not in ("PYTHONPATH", "SENTINEL_ROOT")}
        return subprocess.run(
            [sys.executable, "-I", *args], cwd=self.project, input=stdin, capture_output=True,
            text=True, encoding="utf-8", env=env, timeout=120,
        )

    def test_launcher_runs_the_bundled_package_and_writes_into_the_project(self) -> None:
        result = self._run([str(self.plugin / "launcher.py"), "init", "DEMO"])
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertTrue((self.project / "workspaces" / "DEMO").is_dir())
        self.assertFalse((self.plugin / "workspaces").exists(), "state must never land in the plugin folder")

    def test_hook_from_the_plugin_denies_a_governed_write(self) -> None:
        payload = json.dumps({
            "tool_name": "Write",
            "tool_input": {"file_path": str(self.project / "workspaces" / "DEMO" / "03_specs" / "x.md")},
        })
        result = self._run([str(self.plugin / "hooks" / "deny-governed-artifact-write.py")], payload)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(json.loads(result.stdout)["hookSpecificOutput"]["permissionDecision"], "deny")


class OfflineValidatorTests(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp, True)
        for relative, content in pp.expected_plugin_files(REPO_ROOT).items():
            if "/lib/" in relative or "/skills/" in relative:
                continue  # the validator reads manifests, not the payload
            target = self.tmp / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)

    def _edit(self, relative: str, change) -> None:
        path = self.tmp / relative
        data = json.loads(path.read_text(encoding="utf-8"))
        change(data)
        path.write_text(json.dumps(data), encoding="utf-8")

    def test_the_repo_passes(self) -> None:
        self.assertEqual(pp.plugin_manifest_issues(REPO_ROOT), [])
        self.assertEqual(pp.plugin_manifest_issues(self.tmp), [])

    def test_rejects_a_source_with_dotdot(self) -> None:
        self._edit(pp.MARKETPLACE_FILE, lambda d: d["plugins"][0].update(source="./../plugins/ignite-sentinel"))
        self.assertTrue(any(".." in issue for issue in pp.plugin_manifest_issues(self.tmp)))

    def test_rejects_a_source_without_dot_slash(self) -> None:
        self._edit(pp.MARKETPLACE_FILE, lambda d: d["plugins"][0].update(source="plugins/ignite-sentinel"))
        self.assertTrue(any("./" in issue for issue in pp.plugin_manifest_issues(self.tmp)))

    def test_rejects_an_entry_name_that_differs_from_the_manifest(self) -> None:
        self._edit(f"plugins/{pp.PLUGIN_NAME}/.claude-plugin/plugin.json", lambda d: d.update(name="other"))
        self.assertTrue(any("manifest name" in issue for issue in pp.plugin_manifest_issues(self.tmp)))

    def test_rejects_a_version_in_the_entry(self) -> None:
        self._edit(pp.MARKETPLACE_FILE, lambda d: d["plugins"][0].update(version="1.0.0"))
        self.assertTrue(any("version" in issue for issue in pp.plugin_manifest_issues(self.tmp)))

    def test_rejects_a_homepage_that_is_not_a_url(self) -> None:
        self._edit(f"plugins/{pp.PLUGIN_NAME}/.claude-plugin/plugin.json", lambda d: d.update(homepage="see README"))
        self.assertTrue(any("homepage" in issue for issue in pp.plugin_manifest_issues(self.tmp)))

    def test_rejects_a_reserved_name(self) -> None:
        self._edit(pp.MARKETPLACE_FILE, lambda d: d.update(name="claude-plugins-official"))
        self.assertTrue(any("reserved" in issue for issue in pp.plugin_manifest_issues(self.tmp)))

    def test_rejects_a_top_level_bin(self) -> None:
        (self.tmp / "plugins" / pp.PLUGIN_NAME / "bin").mkdir()
        self.assertTrue(any("bin/" in issue for issue in pp.plugin_manifest_issues(self.tmp)))

    def test_rejects_a_hooks_file_without_the_wrapper(self) -> None:
        relative = f"plugins/{pp.PLUGIN_NAME}/hooks/hooks.json"
        self._edit(relative, lambda d: (d.update(d.pop("hooks"))))
        self.assertTrue(any("hooks" in issue for issue in pp.plugin_manifest_issues(self.tmp)))


class DoctorCheckTests(unittest.TestCase):
    def test_doctor_reports_the_plugin_check_as_pass(self) -> None:
        from sentinel.doctor import claude_plugin_check

        check = claude_plugin_check(REPO_ROOT)
        self.assertEqual(check["status"], "PASS", check["detail"])

    def test_doctor_fails_on_drift(self) -> None:
        from sentinel.doctor import claude_plugin_check

        tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, tmp, True)
        for relative, content in pp.expected_plugin_files(REPO_ROOT).items():
            target = tmp / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(content)
        for name in ("sentinel", CANONICAL_SKILLS_DIR, ".claude/hooks"):
            shutil.copytree(REPO_ROOT / name, tmp / name, ignore=shutil.ignore_patterns("__pycache__"))
        for name in ("pyproject.toml", "LICENSE"):
            shutil.copy(REPO_ROOT / name, tmp / name)
        (tmp / CANONICAL_SKILLS_DIR / "sentinel-views" / "SKILL.md").write_text("changed", encoding="utf-8")
        check = claude_plugin_check(tmp)
        self.assertEqual(check["status"], "FAIL")
        self.assertIn("--plugin", check["detail"])


