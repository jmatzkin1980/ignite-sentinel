"""IMP-313: the clone's deny hook starts Python through the plugin's shim, not a bare `python`.

On many Windows laptops `python` is missing from PATH or is the Microsoft Store alias.
Claude Code runs hook commands through a shell, so the clone uses the same
`python.sh` the plugin ships, generated by `python -m sentinel.adapters`.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import unittest
from pathlib import Path

from sentinel.adapters import CLONE_PYTHON_SHIM, clone_shim_bytes, out_of_sync
from sentinel.plugin_package import PYTHON_SHIM_SCRIPT

ROOT = Path(__file__).resolve().parents[1]


class CloneHookLauncherTests(unittest.TestCase):
    def test_settings_start_the_hook_through_the_shim(self) -> None:
        settings = json.loads((ROOT / ".claude" / "settings.json").read_text(encoding="utf-8"))
        commands = [hook["command"] for entry in settings["hooks"]["PreToolUse"] for hook in entry["hooks"]]
        self.assertEqual(commands, ["sh .claude/hooks/python.sh .claude/hooks/deny-governed-artifact-write.py"])

    def test_the_clone_shim_is_the_plugin_shim(self) -> None:
        self.assertEqual((ROOT / CLONE_PYTHON_SHIM).read_bytes(), PYTHON_SHIM_SCRIPT.encode("utf-8"))
        self.assertEqual(clone_shim_bytes(), PYTHON_SHIM_SCRIPT.encode("utf-8"))
        self.assertFalse([issue for issue in out_of_sync(ROOT) if "python.sh" in issue])

    @unittest.skipUnless(shutil.which("sh"), "needs a POSIX sh, as Claude Code's hooks do")
    def test_the_shim_runs_python(self) -> None:
        result = subprocess.run(
            ["sh", str(ROOT / CLONE_PYTHON_SHIM), "-c", "import sys; print(sys.version_info[0])"],
            capture_output=True, text=True, timeout=60,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout.strip(), "3")


if __name__ == "__main__":
    unittest.main()
