"""IMP-332: a hand edit of a governed artifact is never absorbed silently.

Review 2026-11-16 (findings 2 and 8, journey M7): the next mutating command
re-snapshotted every governed hash, so the `/health` warning vanished and
`/brief`/`/backlog` could overwrite the edit with no copy. And any command that
set `health=CLEAN` cleared a `/health` DIRTY verdict whose cause remained.
"""
import contextlib
import io
import os
import shutil
import tempfile
import unittest
from pathlib import Path

from sentinel.cli import main
from sentinel.core.io import write_text
from sentinel.core.state import read_state
from sentinel.health import run_health
from sentinel.protocols import HAND_EDITS_DIR, postflight_command, preflight_command
from sentinel.workspace import update_state, workspace_path

MARKER = "HAND-EDIT-MARKER-332"


def run(argv: list[str]) -> int:
    with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
        return main(argv)


class HandEditFlowTests(unittest.TestCase):
    def setUp(self) -> None:
        self.old_cwd = Path.cwd()
        self.temp = Path(tempfile.mkdtemp())
        os.chdir(self.temp)
        source = self.temp / "request.md"
        source.write_text(
            "Need a read-only dashboard for support leads. Reduce handling time by 40%. "
            "Acceptance: leads see queue risk before standup.",
            encoding="utf-8",
        )
        self.assertEqual(run(["init", "HED", "--brief-version", "1"]), 0)
        self.assertEqual(run(["ingest", "HED", "--source", str(source)]), 0)
        self.base = workspace_path("HED")
        self.gaps = self.base / "01_discovery" / "gaps.md"

    def tearDown(self) -> None:
        os.chdir(self.old_cwd)
        shutil.rmtree(self.temp, ignore_errors=True)

    def hand_edit_gaps(self) -> None:
        self.gaps.write_text(self.gaps.read_text(encoding="utf-8") + f"\n<!-- {MARKER} -->\n", encoding="utf-8")

    def kept_copies(self) -> list[Path]:
        root = self.base / HAND_EDITS_DIR
        return sorted(p for p in root.rglob("*") if p.is_file()) if root.exists() else []

    def gaps_warnings(self) -> list[str]:
        return [w for w in run_health("HED")["warnings"] if "01_discovery/gaps.md" in w]

    # --- finding 2 / M7 -----------------------------------------------------

    def test_warning_survives_the_next_mutating_command(self):
        self.hand_edit_gaps()
        self.assertTrue(self.gaps_warnings())
        self.assertEqual(run(["gaps", "HED"]), 0)
        # The warning naming the file must still be there after /gaps.
        self.assertTrue(self.gaps_warnings(), "the hand-edit warning was laundered by /gaps")
        # And the hand-edited text is never lost: in the file or in a kept copy.
        texts = [self.gaps.read_text(encoding="utf-8")] + [p.read_text(encoding="utf-8") for p in self.kept_copies()]
        self.assertTrue(any(MARKER in text for text in texts))

    def test_command_that_does_not_write_the_file_keeps_its_old_hash(self):
        self.hand_edit_gaps()
        before = read_state("HED")["artifact_hashes"]["01_discovery/gaps.md"]
        preflight_command("gaps", "HED")
        postflight_command("gaps", "HED", {})  # the command wrote nothing
        self.assertEqual(read_state("HED")["artifact_hashes"]["01_discovery/gaps.md"], before)
        warnings = self.gaps_warnings()
        self.assertTrue(any("edited outside the CLI" in w for w in warnings))
        # The edit is still in place, so no redundant copy is left behind.
        self.assertEqual(self.kept_copies(), [])

    def test_overwritten_edit_is_kept_and_reported_until_the_copy_is_removed(self):
        self.hand_edit_gaps()
        preflight_command("gaps", "HED")
        write_text(self.gaps, "# regenerated by a command\n")  # the command overwrites the edit
        stderr = io.StringIO()
        with contextlib.redirect_stderr(stderr):
            postflight_command("gaps", "HED", {})
        copies = self.kept_copies()
        self.assertEqual(len(copies), 1)
        self.assertEqual(copies[0].relative_to(copies[0].parents[1]).as_posix(), "01_discovery/gaps.md")
        self.assertIn(MARKER, copies[0].read_text(encoding="utf-8"))
        self.assertIn("01_discovery/gaps.md", stderr.getvalue())
        warnings = self.gaps_warnings()
        self.assertEqual(len(warnings), 1)
        self.assertNotIn("edited outside the CLI", warnings[0])  # the command wrote it: registry refreshed
        self.assertIn(HAND_EDITS_DIR, warnings[0])
        copies[0].unlink()
        self.assertEqual(self.gaps_warnings(), [])

    # --- finding 8 ------------------------------------------------------------

    def test_specs_does_not_clean_a_dirty_health_whose_cause_remains(self):
        (self.base / "02_requirements" / "notes.md").write_text("Cut cost by 30%.\n", encoding="utf-8")
        report = run_health("HED")
        self.assertEqual(report["verdict"], "DIRTY")
        self.assertTrue(any("notes.md" in f for f in report["findings"]))
        # A mutating command that sets CLEAN on its own criteria (as /specs and
        # /maturity do) while the /health finding still holds.
        preflight_command("specs", "HED")
        update_state("HED", health="CLEAN")
        postflight_command("specs", "HED", {})
        self.assertEqual(read_state("HED")["health"], "DIRTY")
        self.assertEqual(run(["backlog", "HED"]), 4)

    def test_a_resolved_health_cause_lets_the_command_verdict_stand(self):
        notes = self.base / "02_requirements" / "notes.md"
        notes.write_text("Cut cost by 30%.\n", encoding="utf-8")
        self.assertEqual(run_health("HED")["verdict"], "DIRTY")
        notes.unlink()
        # Recomputed from current findings, not taken from the last writer.
        preflight_command("specs", "HED")
        update_state("HED", health="CLEAN")
        postflight_command("specs", "HED", {})
        self.assertEqual(read_state("HED")["health"], run_health("HED")["verdict"])
        self.assertFalse(any("notes.md" in f for f in run_health("HED")["findings"]))

    def test_raw_metric_finding_clears_once_the_metric_gap_is_closed(self):
        def raw_metric_findings() -> list[str]:
            return [f for f in run_health("HED")["findings"] if f.startswith("Metric without explicit source") and "request" in f]

        self.assertTrue(raw_metric_findings())
        lines = self.gaps.read_text(encoding="utf-8").splitlines()
        closed = [
            line.replace("OPEN", "CLOSED", 1) if line.lstrip("| ").startswith("GAP-METRIC-SOURCE") else line
            for line in lines
        ]
        self.assertNotEqual(lines, closed, "fixture must open GAP-METRIC-SOURCE")
        self.gaps.write_text("\n".join(closed) + "\n", encoding="utf-8")
        self.assertEqual(raw_metric_findings(), [])


if __name__ == "__main__":
    unittest.main()
