#!/usr/bin/env python3
"""Ignite Sentinel plugin launcher (IMP-279).

Generated by `python -m sentinel.adapters --plugin`; do not edit by hand.

It finds the bundled runtime by its own location (`lib/` next to this file), not
through a variable a surface may or may not set, so the same file serves every
surface. Workspaces and outputs land in the current directory: the user's project,
never the plugin folder. `--mcp` starts the MCP server instead of the CLI.
"""
import os
import sys
from pathlib import Path

if sys.version_info < (3, 10):
    sys.exit("Ignite Sentinel needs Python 3.10 or newer.")

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))


def _main(argv):
    if argv[:1] == ["--mcp"]:
        project = os.environ.get("CLAUDE_PROJECT_DIR")
        if project:
            os.chdir(project)
        from sentinel.mcp import main as mcp_main

        return mcp_main(argv[1:])
    from sentinel.cli import main as cli_main

    return cli_main(argv)


if __name__ == "__main__":
    raise SystemExit(_main(sys.argv[1:]))
