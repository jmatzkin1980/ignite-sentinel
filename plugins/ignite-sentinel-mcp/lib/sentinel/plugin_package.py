"""Claude Code plugin and marketplace generator (IMP-279, H14).

The repository doubles as a Claude Code marketplace: `.claude-plugin/marketplace.json`
lists two plugins kept under `plugins/`, and both are *generated* from the sources
the clone already uses — never edited by hand:

- `ignite-sentinel`: the skills (rendered with the `claude-plugin` overlay of
  IMP-278), the read-only hook that stops hand edits of governed artifacts, a
  launcher, and the runtime bundled **in source form** under `lib/sentinel/` so a
  corporate reviewer can audit exactly what runs.
- `ignite-sentinel-mcp`: the MCP server, off by default (`defaultEnabled: false`)
  because it needs the third-party `mcp` package. It carries its own copy of the
  runtime: an installed plugin is cached on its own and cannot reach a sibling.

Regenerate with `python -m sentinel.adapters` (everything) or
`python -m sentinel.adapters --plugin` (only this). `plugin_out_of_sync` is the
drift guard and `plugin_manifest_issues` the offline subset of
`claude plugin validate` that `/doctor` runs without network.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from .adapters import render_skills
from .core.io import parse_json, write_bytes

PLUGIN_NAME = "ignite-sentinel"
MCP_PLUGIN_NAME = "ignite-sentinel-mcp"
MARKETPLACE_NAME = "ignite-sentinel"
MARKETPLACE_FILE = ".claude-plugin/marketplace.json"
PLUGINS_DIR = "plugins"
PLUGIN_NAMES = (PLUGIN_NAME, MCP_PLUGIN_NAME)

OWNER = "jmatzkin1980"
REPOSITORY_URL = "https://github.com/jmatzkin1980/ignite-sentinel"
HOOK_SCRIPT = "deny-governed-artifact-write.py"
CATEGORY = "productivity"
KEYWORDS = ["requirements", "business-analysis", "product", "traceability", "local-first"]

_PACKAGE_SKIP_DIRS = {"__pycache__"}
_PACKAGE_SKIP_SUFFIXES = {".pyc", ".pyo"}

LAUNCHER = '''#!/usr/bin/env python3
"""Ignite Sentinel plugin launcher (IMP-279).

Generated by `python -m sentinel.adapters --plugin`; do not edit by hand.

It finds the bundled runtime by its own location (`lib/` next to this file), not
through a variable a surface may or may not set, so the same file serves every
surface. Workspaces and outputs land in the current directory: the user's project,
never the plugin folder. `--mcp` starts the MCP server instead of the CLI.
"""
import os
import sys
from pathlib import Path

if sys.version_info < (3, 10):
    sys.exit("Ignite Sentinel needs Python 3.10 or newer.")

sys.path.insert(0, str(Path(__file__).resolve().parent / "lib"))


def _main(argv):
    if argv[:1] == ["--mcp"]:
        project = os.environ.get("CLAUDE_PROJECT_DIR")
        if project:
            os.chdir(project)
        from sentinel.mcp import main as mcp_main

        return mcp_main(argv[1:])
    from sentinel.cli import main as cli_main

    return cli_main(argv)


if __name__ == "__main__":
    raise SystemExit(_main(sys.argv[1:]))
'''


def project_version(root: Path) -> str:
    """The package version, read from `pyproject.toml` (stdlib-only, 3.10 has no tomllib)."""
    text = (root / "pyproject.toml").read_text(encoding="utf-8")
    project = re.search(r"^\[project\]\s*$(.*?)(?=^\[|\Z)", text, re.M | re.S)
    match = re.search(r'^version\s*=\s*"([^"]+)"', project.group(1) if project else "", re.M)
    if not match:
        raise ValueError("pyproject.toml has no [project] version")
    return match.group(1)


def _project_description(root: Path) -> str:
    match = re.search(r'^description\s*=\s*"([^"]+)"', (root / "pyproject.toml").read_text(encoding="utf-8"), re.M)
    return match.group(1) if match else "Ignite Sentinel"


def _json_bytes(data: dict) -> bytes:
    return (json.dumps(data, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _package_files(root: Path) -> dict[str, bytes]:
    base = root / "sentinel"
    files: dict[str, bytes] = {}
    for item in sorted(base.rglob("*")):
        if not item.is_file() or _PACKAGE_SKIP_DIRS.intersection(item.relative_to(base).parts):
            continue
        if item.suffix in _PACKAGE_SKIP_SUFFIXES:
            continue
        files[item.relative_to(base).as_posix()] = item.read_bytes()
    return files


def _manifest(root: Path, name: str, description: str, **extra) -> dict:
    manifest = {
        "name": name,
        "displayName": "Ignite Sentinel" if name == PLUGIN_NAME else "Ignite Sentinel MCP",
        "version": project_version(root),
        "description": description,
        "author": {"name": OWNER},
        "homepage": REPOSITORY_URL,
        "repository": REPOSITORY_URL,
        "license": "MIT",
        "keywords": KEYWORDS,
    }
    manifest.update(extra)
    return manifest


def expected_plugin_files(root: Path) -> dict[str, bytes]:
    """Every generated file, keyed by its POSIX path from the repository root."""
    description = _project_description(root)
    mcp_description = (
        "MCP server for Ignite Sentinel. Off by default: it needs the `mcp` package "
        '(`pip install "mcp>=1.2,<3"`) in the Python that runs it.'
    )
    files: dict[str, bytes] = {
        MARKETPLACE_FILE: _json_bytes({
            "name": MARKETPLACE_NAME,
            "owner": {"name": OWNER},
            "description": "Ignite Sentinel: local-first requirements operating framework for AI PODs.",
            "plugins": [
                {"name": PLUGIN_NAME, "source": f"./{PLUGINS_DIR}/{PLUGIN_NAME}", "description": description, "category": CATEGORY},
                {
                    "name": MCP_PLUGIN_NAME,
                    "source": f"./{PLUGINS_DIR}/{MCP_PLUGIN_NAME}",
                    "description": mcp_description,
                    "category": CATEGORY,
                    "defaultEnabled": False,
                },
            ],
        }),
    }
    license_bytes = (root / "LICENSE").read_bytes()
    runtime = _package_files(root)

    main = f"{PLUGINS_DIR}/{PLUGIN_NAME}"
    files[f"{main}/.claude-plugin/plugin.json"] = _json_bytes(_manifest(root, PLUGIN_NAME, description))
    files[f"{main}/hooks/hooks.json"] = _json_bytes({
        "hooks": {
            "PreToolUse": [
                {
                    "matcher": "Write|Edit",
                    "hooks": [{"type": "command", "command": f'python "${{CLAUDE_PLUGIN_ROOT}}/hooks/{HOOK_SCRIPT}"'}],
                }
            ]
        }
    })
    files[f"{main}/hooks/{HOOK_SCRIPT}"] = (root / ".claude" / "hooks" / HOOK_SCRIPT).read_bytes()
    for relative, content in render_skills(root, "claude-plugin").items():
        files[f"{main}/skills/{relative}"] = content

    mcp = f"{PLUGINS_DIR}/{MCP_PLUGIN_NAME}"
    files[f"{mcp}/.claude-plugin/plugin.json"] = _json_bytes(
        _manifest(root, MCP_PLUGIN_NAME, mcp_description, defaultEnabled=False)
    )
    files[f"{mcp}/.mcp.json"] = _json_bytes({
        "mcpServers": {
            "ignite-sentinel": {"command": "python", "args": ["${CLAUDE_PLUGIN_ROOT}/launcher.py", "--mcp"]}
        }
    })

    for base in (main, mcp):
        files[f"{base}/launcher.py"] = LAUNCHER.encode("utf-8")
        files[f"{base}/LICENSE"] = license_bytes
        for relative, content in runtime.items():
            files[f"{base}/lib/sentinel/{relative}"] = content
    return files


def _same(path: Path, content: bytes) -> bool:
    """Equal up to line endings: a Windows checkout (`* text=auto`) turns LF into CRLF."""
    return path.read_bytes().replace(b"\r\n", b"\n") == content.replace(b"\r\n", b"\n")


def _existing_plugin_files(root: Path) -> set[str]:
    found: set[str] = set()
    for name in PLUGIN_NAMES:
        base = root / PLUGINS_DIR / name
        if not base.is_dir():
            continue
        for item in base.rglob("*"):
            relative = item.relative_to(root)
            if item.is_file() and not _PACKAGE_SKIP_DIRS.intersection(relative.parts) and item.suffix not in _PACKAGE_SKIP_SUFFIXES:
                found.add(relative.as_posix())
    return found


def regenerate_plugin(root: Path | None = None) -> dict[str, int]:
    """Write the marketplace and both plugins; remove generated files that no longer exist at the source."""
    root = root or Path.cwd()
    expected = expected_plugin_files(root)
    written = 0
    for relative, content in expected.items():
        destination = root / relative
        if destination.exists() and _same(destination, content):
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        write_bytes(destination, content, root=root)
        written += 1
    removed = 0
    for relative in sorted(_existing_plugin_files(root) - set(expected)):
        (root / relative).unlink()
        removed += 1
    for name in PLUGIN_NAMES:
        base = root / PLUGINS_DIR / name
        if base.is_dir():
            for directory in sorted((d for d in base.rglob("*") if d.is_dir()), key=lambda d: len(d.parts), reverse=True):
                if not any(directory.iterdir()):
                    directory.rmdir()
    return {"written": written, "removed": removed}


def plugin_out_of_sync(root: Path | None = None) -> list[str]:
    """Drift guard: the committed marketplace and plugins must equal a fresh generation."""
    root = root or Path.cwd()
    expected = expected_plugin_files(root)
    issues: list[str] = []
    for relative, content in expected.items():
        path = root / relative
        if not path.exists():
            issues.append(f"missing {relative}")
        elif not _same(path, content):
            issues.append(f"{relative} differs from the generator")
    for relative in sorted(_existing_plugin_files(root) - set(expected)):
        issues.append(f"stale {relative} (not generated)")
    return issues


# --- offline validator: the subset of `claude plugin validate` this repo relies on ---

_RESERVED_PREFIXES = ("claude-", "anthropic-", "anthropics-", "cc-plugin-")
_RESERVED_EXACT = {"claude", "anthropic", "anthropics", "claude-code", "claude-mods"}
_NAME = re.compile(r"\A[a-z0-9]+(?:-[a-z0-9]+)*\Z")
_URL = re.compile(r"\Ahttps?://[^\s/]+\.[^\s/]+(?:/\S*)?\Z")


def _name_issues(kind: str, name: object) -> list[str]:
    if not isinstance(name, str) or not _NAME.match(name):
        return [f"{kind} name {name!r} must be kebab-case"]
    lowered = name.lower()
    words = lowered.split("-")
    if (
        lowered.startswith(_RESERVED_PREFIXES)
        or lowered in _RESERVED_EXACT
        or ("official" in words and ({"claude", "anthropic"} & set(words)))
    ):
        return [f"{kind} name {name!r} is reserved for Anthropic"]
    return []


def _load_json(path: Path, issues: list[str]) -> dict | None:
    try:
        data = parse_json(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        issues.append(f"missing {path.as_posix()}")
        return None
    except ValueError as exc:
        issues.append(f"{path.as_posix()}: invalid JSON ({exc})")
        return None
    if not isinstance(data, dict):
        issues.append(f"{path.as_posix()}: must be a JSON object")
        return None
    return data


def plugin_manifest_issues(root: Path) -> list[str]:
    """Offline checks for the marketplace and every relative-path plugin it lists."""
    issues: list[str] = []
    market = _load_json(root / MARKETPLACE_FILE, issues)
    if market is None:
        return issues
    issues += _name_issues("marketplace", market.get("name"))
    if not isinstance(market.get("owner"), dict) or not market["owner"].get("name"):
        issues.append("marketplace: owner.name is required")
    entries = market.get("plugins")
    if not isinstance(entries, list) or not entries:
        return issues + ["marketplace: plugins must be a non-empty list"]
    for index, entry in enumerate(entries):
        label = f"plugins[{index}]"
        if not isinstance(entry, dict):
            issues.append(f"{label}: must be an object")
            continue
        name = entry.get("name")
        issues += _name_issues(label, name)
        if "version" in entry:
            issues.append(f"{label}: version belongs in plugin.json only (one source)")
        source = entry.get("source")
        if not isinstance(source, str):
            issues.append(f"{label}: source must be a relative path in this repo")
            continue
        if ".." in Path(source).parts or ".." in source.split("/"):
            issues.append(f'{label}: source contains ".." ({source})')
            continue
        if not source.startswith("./"):
            issues.append(f"{label}: source must start with ./ ({source})")
            continue
        plugin_dir = root / source[2:]
        if not plugin_dir.is_dir():
            issues.append(f"{label}: source path does not exist ({source})")
            continue
        manifest = _load_json(plugin_dir / ".claude-plugin" / "plugin.json", issues)
        if manifest is None:
            continue
        if manifest.get("name") != name:
            issues.append(f"{label}: entry name {name!r} differs from manifest name {manifest.get('name')!r}")
        if not manifest.get("version"):
            issues.append(f"{label}: plugin.json has no version")
        homepage = manifest.get("homepage")
        if homepage is not None and not (isinstance(homepage, str) and _URL.match(homepage)):
            issues.append(f"{label}: homepage {homepage!r} is not a URL")
        if (plugin_dir / "bin").exists():
            issues.append(f"{label}: top-level bin/ is refused by claude.ai organization sync")
        hooks_file = plugin_dir / "hooks" / "hooks.json"
        if hooks_file.exists():
            hooks = _load_json(hooks_file, issues)
            if hooks is not None and not isinstance(hooks.get("hooks"), dict):
                issues.append(f"{label}: hooks/hooks.json must wrap the event map in a top-level \"hooks\" key")
    return issues
